export const REGIONES_CHILE = CHILE_REGIONS.map((r) => r.name);

/**
 * Obtiene las comunas pertenecientes a una región específica.
 */
export function getCommunesForRegion(regionName?: string | null): string[] {
  if (!regionName) return [];
  const region = CHILE_REGIONS.find(
    (r) => r.name.toLowerCase() === regionName.trim().toLowerCase()
  );
  return region ? region.communes : [];
}

/**
 * Verifica si una comuna pertenece a una región dada.
 */
export function isValidCommuneInRegion(commune?: string | null, regionName?: string | null): boolean {
  if (!commune || !regionName) return false;
  const communes = getCommunesForRegion(regionName);
  return communes.some((c) => c.toLowerCase() === commune.trim().toLowerCase());
}
